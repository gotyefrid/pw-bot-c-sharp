namespace BotCH.Core.Actions;

/// <summary>
/// Чем действие управляет игрой — передаётся в <see cref="GameAction.Send"/>. Пока только вызовы функций игры
/// (<see cref="Calls"/>). Потом сюда добавится ввод с клавиатуры («нажать клавишу» — основа кликера: всё, что клиент делает
/// клавишей, через функции делать незачем) — новым свойством и новым действием, без правки исполнителя, мозга и
/// остальных действий. Какой формы будет ввод (клавиша, комбинация, удержание), решим, когда до него дойдём.
/// </summary>
public sealed class GameControl(IGameActions calls)
{
    /// <summary>Вызовы функций игры: пакеты и «работы» персонажа.</summary>
    public IGameActions Calls { get; } = calls;
}
